function estimateReadingMinutes(body: string[]): number {
  return Math.max(4, Math.ceil(body.join("").length / 430));
}

export const articles: Article[] = baseArticles.map((article) => {
  const body = [...article.body, ...(articleBodyAdditions[article.slug] ?? [])];
  return {
    ...article,
    body,
    readingMinutes: Math.max(article.readingMinutes, estimateReadingMinutes(body)),
  };
});

export function getArticles(): Article[] {
  return [...articles].sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
}

export function searchArticles(query: string): Article[] {
  const keywords = query
    .normalize("NFKC")
    .trim()
    .toLocaleLowerCase("ko-KR")
    .split(/\s+/)
    .filter(Boolean);

  if (keywords.length === 0) {
    return [];
  }

  return getArticles()
    .map((article) => {
      const title = article.title.normalize("NFKC").toLocaleLowerCase("ko-KR");
      const tags = article.tags.join(" ").normalize("NFKC").toLocaleLowerCase("ko-KR");
      const categoryName = article.category.name.normalize("NFKC").toLocaleLowerCase("ko-KR");
      const description = [article.summary, ...article.body].join(" ").normalize("NFKC").toLocaleLowerCase("ko-KR");
      const searchableText = `${title} ${tags} ${categoryName} ${description}`;

      if (!keywords.every((keyword) => searchableText.includes(keyword))) {
        return null;
      }

      const score = keywords.reduce(
        (total, keyword) =>
          total +
          (title.includes(keyword) ? 8 : 0) +
          (tags.includes(keyword) ? 4 : 0) +
          (categoryName.includes(keyword) ? 2 : 0) +
          (description.includes(keyword) ? 1 : 0),
        0,
      );

      return { article, score };
    })
    .filter((result): result is { article: Article; score: number } => result !== null)
    .sort((a, b) => b.score - a.score || b.article.publishedAt.localeCompare(a.article.publishedAt))
    .map(({ article }) => article);
}

export function getArticleBySlug(slug: string): Article | undefined {
  return articles.find((article) => article.slug === slug);
}

export function getFeaturedArticles(): Article[] {
  return getArticles().filter((article) => article.featured).slice(0, 6);
}

export function getPopularArticles(): Article[] {
  return getArticles().filter((article) => article.popular).slice(0, 8);
}

export function getArticlesByCategory(categorySlug: string): Article[] {
  return getArticles().filter((article) => article.category.slug === categorySlug);
}

export function getRelatedArticles(article: Article, limit = 4): Article[] {
  return getArticles()
    .filter((candidate) => candidate.slug !== article.slug)
    .map((candidate) => ({
      article: candidate,
      score:
        (candidate.category.slug === article.category.slug ? 3 : 0) +
        candidate.tags.filter((tag) => article.tags.includes(tag)).length,
    }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score || b.article.publishedAt.localeCompare(a.article.publishedAt))
    .slice(0, limit)
    .map((item) => item.article);
}

export function getTags(): Array<{ slug: string; name: string; count: number }> {
  const counts = new Map<string, number>();
  for (const article of articles) {
    for (const tag of article.tags) {
      counts.set(tag, (counts.get(tag) ?? 0) + 1);
    }
  }

  return Array.from(counts.entries())
    .map(([name, count]) => ({ name, slug: tagSlug(name), count }))
    .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name, "ko"));
}

export function getArticlesByTag(tagSlugValue: string): Article[] {
  const tag = getTags().find((item) => item.slug === tagSlugValue);
  if (!tag) {
    return [];
  }
  return getArticles().filter((article) => article.tags.includes(tag.name));
}

export function articlePath(article: Pick<Article, "slug">): string {
  return `/articles/${article.slug}`;
}

export function articleCategoryPath(categoryInput: Pick<ArticleCategory, "slug">): string {
  return `/categories/${categoryInput.slug}`;
}

export function tagSlug(tag: string): string {
  return tag
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9가-힣]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function tagPath(tag: string): string {
  return `/tags/${tagSlug(tag)}`;
}

